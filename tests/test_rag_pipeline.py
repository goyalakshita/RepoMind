def test_index_repository(pipeline, sample_repository):
    result = pipeline.index_repository(str(sample_repository))

    assert result["files_processed"] >= 1
    assert result["chunks_created"] == 2
    assert result["chunks_stored"] == 2


def test_ask_question(pipeline, sample_repository):
    pipeline.index_repository(str(sample_repository))

    result = pipeline.ask_question(
        "How does authentication work?"
    )

    assert "answer" in result
    assert "sources" in result
    assert len(result["sources"]) > 0


def test_question_before_indexing(pipeline):
    with pytest.raises(ValueError):
        pipeline.ask_question("Explain authentication")


def test_clear_database(pipeline, sample_repository):
    pipeline.index_repository(str(sample_repository))

    pipeline.clear_database()

    assert pipeline.repository_path is None
    assert pipeline.vector_store.get_collection_count() == 0


def test_empty_repository(pipeline, tmp_path):
    with pytest.raises(ValueError):
        pipeline.index_repository(str(tmp_path))
